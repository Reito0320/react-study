const examples: Record<string, string> = {
  'basic-01': '空入力を拒否する処理を一時的に外す。エラー表示だけ残してタスクが追加されても、テストは検出できる？',
  'basic-02': '編集・削除の対象をIDではなくタイトルで選ぶ。同名タスクが2件あるとき、誤った更新を検出できる？',
  'basic-03': '完了チェックだけを変えて未完了件数を更新しない。表示の食い違いを検出できる？',
  'basic-04': '検索条件の片方を無視する。検索語と完了状態を組み合わせたテストは失敗する？',
  'basic-05': '期限を解除する処理を無効にする。設定だけでなく解除も検証できている？',
  'basic-06': '削除APIが成功を返すだけでデータを削除しないようにする。再取得で検出できる？',
};
export default function TestChallenge({ lessonId }: { lessonId: string }) {
  return <details className="test-challenge" key={lessonId}>
    <summary>任意：そのテスト、不具合を見つけられる？</summary>
    <p>{examples[lessonId] ?? 'この章の要件を1つ選び、その処理だけを一時的に無効にする。対応するテストが失敗するか予想してみよう。'}</p>
    <ol>
      <li>まず通常の実装で対象テストを成功させ、変更前のコードを保存する。</li>
      <li>プロダクトコードに上の不具合を1つだけ入れ、右側のコマンドを実行する。テストは変更しない。</li>
      <li>意図したexpectが失敗したら検出成功。構文エラーや別の理由の失敗は区別する。</li>
      <li>成功したままなら、元の実装へ戻して不足する検証を追加し、もう一度試す。</li>
      <li>最後は必ず不具合を元に戻し、再実行して緑に戻ることを確認する。</li>
    </ol>
    <p className="muted">この挑戦は進捗の必須条件ではありません。1つ検出できても、すべての不具合を検出できる保証ではありません。</p>
  </details>;
}
